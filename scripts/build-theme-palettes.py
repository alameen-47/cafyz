#!/usr/bin/env python3
"""Builds web-v2/src/styles/theme-palettes.css: the extra dark themes.

Each theme is the base dark theme (the `html.dark` block in theme-modes.css) with its violet
family turned to another hue. Status colours (green, amber, red) and anything outside the
violet-to-blue range are left alone, so a theme can never drift from the base one: change a
token there, run this script, and every theme follows.

    python3 scripts/build-theme-palettes.py
"""
import colorsys
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "web-v2/src/styles/theme-modes.css"
OUT = ROOT / "web-v2/src/styles/theme-palettes.css"

# hue: where the violet family lands. sat: how much colour to keep. fill: how much lighter or
# darker the fill colours (buttons, gradients) are, so white text on them stays readable in
# hues that look brighter than violet. art: hue turn for the photographed sidebar strip. extra: tokens set by hand (the second accent and its uses).
THEMES = {
    "ocean": dict(
        label="Midnight Blue", hue=214, sat=0.92, fill=0.96, art="hue-rotate(-52deg) saturate(1.1)",
        extra={"--cafyz-brand-2": "#22d3ee", "--cafyz-brand-2-rgb": "34, 211, 238", "--chart-2": "#22d3ee"},
    ),
    "emerald": dict(
        label="Emerald", hue=160, sat=0.86, fill=0.62, art="hue-rotate(-108deg) saturate(0.9)",
        extra={"--cafyz-brand-2": "#f5c451", "--cafyz-brand-2-rgb": "245, 196, 81", "--chart-2": "#f5c451"},
    ),
    "ember": dict(
        label="Ember", hue=16, sat=0.88, fill=0.9, art="hue-rotate(108deg) saturate(1.05)",
        extra={"--cafyz-brand-2": "#ffc857", "--cafyz-brand-2-rgb": "255, 200, 87", "--chart-2": "#ffc857"},
    ),
}

# Tokens that keep their meaning in every theme.
KEEP = re.compile(r"--cafyz-(danger|warning|success|info|on-gradient|banner-expired|brand-2|art-filter)|--destructive|--chart-2")
SOURCE_HUE = 265.0  # centre of the base theme's violet family
# Fill colours: white text sits on these.
FILL = re.compile(r"^--cafyz-(gradient|brand-deep|brand-deep-rgb|brand-alt|brand-alt-rgb)$|^--(primary|sidebar-primary|chart-1|chart-3)$")


def shift(r, g, b, theme, fill=False):
    h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    deg = h * 360
    if s < 0.08 or not (205 <= deg <= 300):
        return r, g, b
    new_h = (theme["hue"] + (deg - SOURCE_HUE) * 0.35) % 360
    if fill:
        l *= theme["fill"]
    nr, ng, nb = colorsys.hls_to_rgb(new_h / 360, l, min(1.0, s * theme["sat"]))
    return round(nr * 255), round(ng * 255), round(nb * 255)


def recolour(value, theme, fill=False):
    def hex_sub(m):
        h = m.group(1)
        r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
        return "#%02x%02x%02x" % shift(r, g, b, theme, fill)

    def rgb_sub(m):
        r, g, b = shift(int(m.group(2)), int(m.group(3)), int(m.group(4)), theme, fill)
        return f"{m.group(1)}{r}, {g}, {b}"

    value = re.sub(r"#([0-9a-fA-F]{6})\b", hex_sub, value)
    value = re.sub(r"(rgba?\()(\d+), ?(\d+), ?(\d+)", rgb_sub, value)
    # bare "r, g, b" triplets (the -rgb tokens)
    if re.fullmatch(r"\s*\d+, ?\d+, ?\d+\s*", value):
        r, g, b = shift(*[int(x) for x in value.split(",")], theme, fill)
        value = f" {r}, {g}, {b}"
    return value


def main():
    css = SRC.read_text()
    start = css.index("html.dark,\nhtml:not(.light) {")
    end = css.index("\n}\n", start)
    body = css[css.index("{", start) + 1:end]
    decls = re.findall(r"(--[\w-]+):([^;]+);", body, re.S)

    out = [
        "/* GENERATED by scripts/build-theme-palettes.py from the dark theme in theme-modes.css.",
        " * Do not edit by hand: change the base theme or the script, then run the script.",
        " *",
        " * The extra dark themes. They apply once someone is signed in (html[data-signed-in]), so",
        " * the sign-in screen keeps its own look. The picker is on the Account screen. */",
        "",
    ]
    for key, theme in THEMES.items():
        out.append(f"/* {theme['label']} */")
        out.append(f'html.dark[data-signed-in][data-palette="{key}"] {{')
        for name, value in decls:
            if name in theme["extra"] or KEEP.search(name):
                continue
            new = recolour(value, theme, bool(FILL.search(name)))
            if new != value:
                out.append(f"  {name}:{new};")
        for name, value in theme["extra"].items():
            out.append(f"  {name}: {value};")
        out.append(f"  --cafyz-art-filter: {theme['art']};")
        out.append("}")
        out.append("")
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
